"""
CodeAgent — writes, saves, and runs code.
Args: {task: str, language: str = "python", run: bool = False, filename: str = None}
"""

import os
import subprocess
import tempfile
import sys

JARVIS_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CODE_OUTPUT_DIR = os.path.join(JARVIS_DIR, "agent_outputs", "code")
os.makedirs(CODE_OUTPUT_DIR, exist_ok=True)


class CodeAgent:
    def __init__(self, llm=None):
        self.llm = llm

    def _write_code(self, task: str, language: str) -> str:
        """Use LLM to write code for the task."""
        system = (
            f"You are an expert {language} developer. Write clean, working code for the task.\n"
            "Output ONLY the raw code — no markdown, no explanation, no backticks.\n"
            "The code must be self-contained and immediately runnable.\n"
            "Add a comment at the top: # Generated by Jarvis CodeAgent"
        )
        try:
            response = self.llm.invoke([
                ("system", system),
                ("user", task)
            ]).content.strip()
            # Strip markdown fences if LLM adds them anyway
            if response.startswith("```"):
                lines = response.split("\n")
                response = "\n".join(lines[1:-1] if lines[-1] == "```" else lines[1:])
            return response.strip()
        except Exception as e:
            return f"# CodeAgent LLM error: {e}\nprint('code generation failed')"

    def _run_code(self, code: str, language: str, filepath: str) -> str:
        """Execute the code and capture output."""
        try:
            if language in ("python", "py"):
                result = subprocess.run(
                    [sys.executable, filepath],
                    capture_output=True, text=True, timeout=30,
                    cwd=JARVIS_DIR
                )
            elif language in ("javascript", "js", "node"):
                result = subprocess.run(
                    ["node", filepath],
                    capture_output=True, text=True, timeout=30,
                    cwd=JARVIS_DIR
                )
            elif language in ("powershell", "ps1"):
                result = subprocess.run(
                    ["powershell", "-NoProfile", "-File", filepath],
                    capture_output=True, text=True, timeout=30
                )
            elif language in ("batch", "bat", "cmd"):
                result = subprocess.run(
                    ["cmd", "/c", filepath],
                    capture_output=True, text=True, timeout=30
                )
            else:
                return f"⚠️ Can't auto-run {language} — code saved to {filepath}"

            out = result.stdout.strip()
            err = result.stderr.strip()
            if result.returncode == 0:
                return f"✅ Ran successfully.\nOutput:\n{out}" if out else "✅ Ran successfully (no output)."
            else:
                return f"❌ Exit code {result.returncode}\nSTDOUT: {out}\nSTDERR: {err}"
        except subprocess.TimeoutExpired:
            return "⏱️ Code timed out after 30s — might be an infinite loop or waiting for input"
        except FileNotFoundError as e:
            return f"❌ Runtime not found: {e}"
        except Exception as e:
            return f"❌ Run error: {e}"

    def run(self, args: dict) -> str:
        task     = args.get("task", "")
        language = args.get("language", "python").lower().strip()
        should_run = str(args.get("run", "false")).lower() in ("true", "1", "yes")
        filename = args.get("filename", None)

        if not task:
            return "ERROR: CodeAgent needs a 'task' argument"

        # Write the code
        code = self._write_code(task, language)

        # Determine file extension
        ext_map = {
            "python": "py", "py": "py",
            "javascript": "js", "js": "js", "node": "js",
            "powershell": "ps1", "ps1": "ps1",
            "batch": "bat", "bat": "bat", "cmd": "bat",
            "bash": "sh", "sh": "sh",
        }
        ext = ext_map.get(language, language)

        # Save file
        if filename:
            filepath = os.path.join(CODE_OUTPUT_DIR, filename if "." in filename else f"{filename}.{ext}")
        else:
            import time
            fname = f"jarvis_code_{int(time.time())}.{ext}"
            filepath = os.path.join(CODE_OUTPUT_DIR, fname)

        with open(filepath, "w", encoding="utf-8") as f:
            f.write(code)

        result_lines = [f"📝 Code written to: {filepath}"]
        result_lines.append(f"\n```{language}\n{code[:800]}{'...' if len(code) > 800 else ''}\n```")

        if should_run:
            run_result = self._run_code(code, language, filepath)
            result_lines.append(f"\n{run_result}")

        return "\n".join(result_lines)
